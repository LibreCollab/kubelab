export interface KnowledgeQuestion {
  id: string;
  domainId: string;
  prompt: string;
  options: string[];
  answer: number;
  explanation: string;
  lessonId: string;
  lessonTitle: string;
  unit: string;
  label: string;
}

function buildKnowledgeQuestions(seeds: KnowledgeQuestionSeed[]): KnowledgeQuestion[] {
  const cursors = new Map<string, number>();
  return seeds.map((seed) => {
    const position = cursors.get(seed.domainId) ?? 0;
    cursors.set(seed.domainId, position + 1);
    const options = [...seed.wrong];
    options.splice(position % 4, 0, seed.correct);
    return {
      id: seed.id,
      domainId: seed.domainId,
      prompt: seed.prompt,
      options,
      answer: position % 4,
      explanation: seed.explanation,
      lessonId: seed.lessonId,
      lessonTitle: seed.lessonTitle,
      unit: seed.unit,
      label: seed.label,
    };
  });
}

